// Backwards-compatible alias
export const COMMON_WORDS = STANDARD_WORDS;

export const PUNCTUATION_MARKS = ['.', ',', ';', '!', '?', '-', '"', "'"];

export function getWordPool(difficulty: DifficultyOption = 'standard'): readonly string[] {
  switch (difficulty) {
    case 'expert':
      return EXPERT_WORDS;
    case 'advanced':
      return ADVANCED_WORDS;
    default:
      return STANDARD_WORDS;
  }
}

export function generateWords(
  count: number,
  options: { difficulty?: DifficultyOption; punctuation?: boolean; numbers?: boolean } = {}
): string[] {
  const pool = getWordPool(options.difficulty);
  const words: string[] = [];
  let lastWord = '';

  for (let i = 0; i < count; i++) {
    let word = '';
    // Prevent back-to-back repeats
    let attempts = 0;
    do {
      word = pool[Math.floor(Math.random() * pool.length)];
      attempts++;
    } while (word === lastWord && attempts < 10);
    lastWord = word;

    if (options.numbers && Math.random() < 0.15) {
      word = (Math.floor(Math.random() * 900) + 10).toString();
    }

    if (options.punctuation && Math.random() < 0.2) {
      const p = PUNCTUATION_MARKS[Math.floor(Math.random() * PUNCTUATION_MARKS.length)];
      if (p === '"' || p === "'") {
        word = `${p}${word}${p}`;
      } else {
        word = `${word}${p}`;
      }
      if (Math.random() < 0.3) {
        word = word.charAt(0).toUpperCase() + word.slice(1);
      }
    }

    words.push(word);
  }

  return words;
}

export function generateWeakKeysWords(weakKeys: string[], count: number = 25): string[] {
  if (weakKeys.length === 0) return generateWords(count);
  const lowerWeakKeys = weakKeys.map((k) => k.toLowerCase());
  const matchingWords = STANDARD_WORDS.filter((word) =>
    lowerWeakKeys.some((k) => word.toLowerCase().includes(k))
  );

  const pool = matchingWords.length >= 8 ? matchingWords : STANDARD_WORDS;
  const result: string[] = [];
  let lastWord = '';

  for (let i = 0; i < count; i++) {
    let w = '';
    if (Math.random() < 0.7 && pool.length > 0) {
      let attempts = 0;
      do {
        w = pool[Math.floor(Math.random() * pool.length)];
        attempts++;
      } while (w === lastWord && attempts < 5);
      result.push(w);
    } else {
      const randKey = lowerWeakKeys[Math.floor(Math.random() * lowerWeakKeys.length)];
      const fillers = ['a', 'e', 'i', 'o', 'u', 'r', 's', 't', 'n'];
      const f1 = fillers[Math.floor(Math.random() * fillers.length)];
      const f2 = fillers[Math.floor(Math.random() * fillers.length)];
      w = `${f1}${randKey}${f2}`;
      result.push(w);
    }
    lastWord = w;
  }

  return result;
}
